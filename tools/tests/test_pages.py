    # R1
    def test_a_claim_id_that_is_a_path_fails_the_build_and_writes_nothing_outside(self):
        for bad in ("../y.example", "../../../escaped"):
            with self.subTest(bad=bad):
                rewrite_rows(self.run / "claims.jsonl", lambda r: {**r, "id": bad} if r["id"] == "C-003" else r)
                remanifest(self.run)
                with self.assertRaisesRegex(B.BuildError, "claims.jsonl.*not a claim id"):
                    B.build(self.root, self.out)
                self.assertEqual(sorted(p.name for p in self.out.parent.iterdir()), sorted(["kit", "repo", "src-x.example", "dist"][:4])
                                 if self.out.exists() else sorted(["kit", "repo", "src-x.example"]))
                rewrite_rows(self.run / "claims.jsonl", lambda r: {**r, "id": "C-003"} if r["id"] == bad else r)
                remanifest(self.run)

