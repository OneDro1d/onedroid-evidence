class Links(unittest.TestCase):
    """I-7: internal links and anchors resolve in the build; other site paths are landing pages on the list."""

    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        t = pathlib.Path(self.tmp.name)
        self.kit = mock.patch.object(B, "KIT", clean_kit(t / "kit"))
        self.kit.start()
        self.root = t / "repo"
        self.root.mkdir()
        make_domain(self.root)

    def tearDown(self):
        self.kit.stop()
        self.tmp.cleanup()

    def with_link(self, href):
        real = B.page_html

        def adds(*a, **k):
            return real(*a, **k).replace("</main>", f'<p><a href="{href}">x</a></p>\n</main>', 1)
        with mock.patch.object(B, "page_html", adds):
            return [f for f in B.check(self.root) if f.startswith("I-7 ")]

    def test_clean(self):
        self.assertEqual([f for f in B.check(self.root) if f.startswith("I-7 ")], [])

    def test_a_dead_evidence_link(self):
        self.assertEqual(self.with_link("/evidence/nowhere"), ["I-7 evidence/x.example.html: /evidence/nowhere does not resolve"])

    def test_a_missing_anchor(self):
        self.assertEqual(self.with_link("/evidence/x.example#C-999"),
                         ["I-7 evidence/x.example.html: /evidence/x.example#C-999 has no such anchor"])
        self.assertEqual(self.with_link("#C-999"), ["I-7 evidence/x.example.html: #C-999 has no such anchor"])

    def test_good_links(self):
        for href in ("/evidence/x.example#C-001", "#C-002", "/evidence/x.example.json", "/evidence/x.example/C-003", "/evidence#pages",
                     "/argus#install", "https://onedroid.ai/evidence/x.example/runs", "https://example.com/x", "mailto:a@b.c"):
            with self.subTest(href=href):
                self.assertEqual(self.with_link(href), [])

    def test_a_class_name_is_not_an_anchor(self):
        self.assertEqual(self.with_link("#cs-table"), ["I-7 evidence/x.example.html: #cs-table has no such anchor"])

    def test_a_site_path_not_on_the_landing_list(self):
        self.assertEqual(self.with_link("/blog"), ["I-7 evidence/x.example.html: /blog is not a built page or a landing path"])

    def test_a_canonical_url_that_does_not_resolve(self):
        self.assertEqual(self.with_link("https://onedroid.ai/evidence/nowhere"),
                         ["I-7 evidence/x.example.html: https://onedroid.ai/evidence/nowhere does not resolve"])

    def test_the_real_repo_has_no_dead_link(self):
        self.assertEqual([f for f in B.check(REPO) if f.startswith("I-7 ")], [])


def remanifest(run):
    """Rewrite a run folder's manifest.sha256 so I-4 holds after a fixture edits the record."""
    import hashlib
    lines = [f"{hashlib.sha256(p.read_bytes()).hexdigest()}  {p.name}" for p in sorted(run.iterdir())
             if p.is_file() and p.name != "manifest.sha256"]
    (run / "manifest.sha256").write_text("".join(l + "\n" for l in lines), encoding="utf-8")


def rewrite_rows(path, change):
    rows = [json.loads(l) for l in path.read_text(encoding="utf-8").splitlines() if l.strip()]
    path.write_text("".join(json.dumps(r) + "\n" for r in (change(r) for r in rows) if r is not None), encoding="utf-8")


