        rewrite_rows(self.run / "verdicts.jsonl", lambda r: {**r, "withdrawn": True, "ruled": True} if r["id"] == "C-003" else r)
        remanifest(self.run)
        B.build(self.root, self.out)
        html = (self.out / "evidence" / "x.example" / "C-003.html").read_text(encoding="utf-8")
        self.assertNotIn('href="javascript:', html)
