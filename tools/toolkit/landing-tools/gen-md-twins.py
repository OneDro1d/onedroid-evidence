#!/usr/bin/env python3
"""Generate a Markdown twin (<page>.md) for every page listed in gen-llms-full.py.

WHY THIS EXISTS, AND WHY IT REVERSES A RECORDED DECISION
--------------------------------------------------------
gen-llms-full.py's docstring records that per-page Markdown twins were DECLINED:

    "the site is hand-written HTML with no generator, so twins would have nothing to be
     derived from — and a twin is what an agent reads while humans read the HTML, so a
     stale twin serves wrong content to exactly its audience with no feedback loop."

Both halves of that objection are answered rather than overruled:

  * "nothing to be derived from" — no longer true. gen-llms-full.py IS the generator, and
    this script imports its extractor rather than reimplementing one. The twins are
    DERIVED from the same <main> of the same HTML, by the same code.
  * "no feedback loop" — --check is the feedback loop, identical to its sibling's. A twin
    cannot silently drift if a pre-deploy check fails when it does.

WHAT IT BUYS
------------
Measured 2026-08-20: docs.stripe.com/payments/quickstart returns text/markdown at 69,714
bytes to a ClaudeBot user-agent and text/html at 770,695 bytes to a browser — 11.1x. The
same negotiation is live on Vercel's and Anthropic's docs. This is the agent-readable-web
channel with reproducible evidence behind it, as against llms.txt, where an instrumented
study of 137,210 domains found 97% of published files received zero requests and nothing
probes for a missing one.

    python3 tools/gen-md-twins.py            # regenerate every <page>.md
    python3 tools/gen-md-twins.py --check    # exit 1 if any twin is stale

Serving is wired in middleware.js: only a request carrying `Accept: text/markdown` is
rewritten to the twin; everyone else, AI fetchers included, gets the HTML, and the `.md`
URL is always there (linked from each page head as rel="alternate"). The user-agent
rule that also sent AI bots the twin (2026-08-21 to 2026-10-27) was dropped after the
27 Oct 2026 ranking test: ChatGPT, Perplexity and Copilot could not read a text/markdown
page they were handed, while Gemini, which got the HTML, read it (middleware.js header).
Stdlib only, like its siblings.
"""

import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SIBLING = Path(__file__).resolve().parent / "gen-llms-full.py"

# Import the sibling generator by path: its filename has hyphens, so it is not importable
# by name. Reusing its extractor is the point — two extractors would be two behaviours.
_spec = importlib.util.spec_from_file_location("gen_llms_full", SIBLING)
_gen = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_gen)

BANNER = (
    "<!-- GENERATED by tools/gen-md-twins.py from {source}. The HTML page is "
    "authoritative; if this file disagrees with it, this file is stale. -->\n"
)


def twin_path(url):
    """/ -> index.md ; /docs -> docs.md"""
    return ROOT / ("index.md" if url == "/" else url.lstrip("/") + ".md")


def render(filename, url):
    source = (ROOT / filename).read_text(encoding="utf-8")
    parser = _gen.MainExtractor()
    parser.feed(source)
    body = parser.text()
    if not body:
        sys.stderr.write("EMPTY <main>: %s — refusing to emit a hollow twin\n" % filename)
        sys.exit(2)

    out = [BANNER.format(source=filename)]
    out.append("# %s\n" % _gen.title(source))
    description = _gen.meta(source, "description")
    if description:
        out.append("\n> %s\n" % description)
    out.append("\nCanonical: https://onedroid.ai%s\n" % url)
    out.append("\n%s\n" % body)
    return "".join(out)


def main():
    checking = "--check" in sys.argv
    stale = []
    written = 0

    for filename, url in _gen.PAGES:
        if not (ROOT / filename).exists():
            sys.stderr.write("MISSING: %s (listed in gen-llms-full.PAGES)\n" % filename)
            return 2
        generated = render(filename, url)
        out = twin_path(url)
        if checking:
            if not out.exists() or out.read_text(encoding="utf-8") != generated:
                stale.append(out.relative_to(ROOT).as_posix())
        else:
            out.write_text(generated, encoding="utf-8")
            written += 1

    if checking:
        if stale:
            sys.stderr.write(
                "STALE twins (%d): %s\nRun: python3 tools/gen-md-twins.py\n"
                % (len(stale), ", ".join(stale)))
            return 1
        sys.stdout.write("OK: all %d Markdown twins match the HTML.\n" % len(_gen.PAGES))
        return 0

    sys.stdout.write("Wrote %d Markdown twins.\n" % written)
    return 0


if __name__ == "__main__":
    sys.exit(main())
